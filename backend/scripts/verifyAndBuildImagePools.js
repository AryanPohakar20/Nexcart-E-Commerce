async function checkAll() {
  const allUrls = [];
  for (const [cat, urls] of Object.entries(VERIFIED_IMG)) {
    urls.forEach(u => allUrls.push({ cat, u }));
  }
  console.log(`Checking ${allUrls.length} total URLs across 12 categories...`);

  const results = await Promise.all(
    allUrls.map(async ({ cat, u }) => {
      try {
        const res = await fetch(u, { method: 'HEAD' });
        return { cat, u, status: res.status };
      } catch (err) {
        return { cat, u, status: 500, error: err.message };
      }
    })
  );

  const failed = results.filter(r => r.status !== 200);
  console.log(`\nVerified URLs: ${results.length - failed.length} / ${results.length} are 200 OK`);
  if (failed.length > 0) {
    console.error(`❌ Failed URLs (${failed.length}):`, failed);
    process.exit(1);
  } else {
    console.log(`✅ 100% OF IMAGE URLS ARE VALID AND ACCESSIBLE!`);
  }
}

checkAll().catch(console.error);
